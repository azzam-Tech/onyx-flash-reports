/* =====================================================================
   Onyx Pro - استعلامات أدلة قرائية (READ-ONLY) لكشف مصدر أجهزة الموبايل
   الغرض : تتبّع كيف/متى دخلت الأجهزة تحت الموديولات (MOD_ID) 74 و 80
   ملاحظة: كل ما يلي SELECT فقط - لا يعدّل أي بيانات. آمن على الإنتاج.
   ===================================================================== */


/* ---------------------------------------------------------------------
   (1) سجل الأجهزة كاملاً موزّعاً حسب الموديول + حقول التدقيق
   يكشف: كم جهازاً تحت كل MOD_ID، ومن أي طرفية، وبأي توقيت تفعيل.
   --------------------------------------------------------------------- */
SELECT MOD_ID,
       SEQ_NO,
       IMEI,
       DVC_OWNER,
       ACTIVATION_DATE,
       CASE NVL(INACTIVE,0) WHEN 1 THEN 'موقوف' ELSE 'نشط' END AS الحالة,
       UP_DATE,
       UP_TRMNL_NM
FROM   IAS_SYS.IAS_OBJ_HND_DVC
ORDER  BY MOD_ID, SEQ_NO;


/* ---------------------------------------------------------------------
   (2) عدد الأجهزة النشطة لكل موديول
   لو ظهر أكثر من MOD_ID كلٌّ منه بجهازين = مؤشر مضاعفة السعة عبر الموديولات.
   --------------------------------------------------------------------- */
SELECT MOD_ID,
       COUNT(*)                                              AS إجمالي,
       SUM(CASE NVL(INACTIVE,0) WHEN 0 THEN 1 ELSE 0 END)    AS النشط,
       MIN(ACTIVATION_DATE)                                  AS أول_تفعيل,
       MAX(ACTIVATION_DATE)                                  AS آخر_تفعيل
FROM   IAS_SYS.IAS_OBJ_HND_DVC
GROUP  BY MOD_ID
ORDER  BY MOD_ID;


/* ---------------------------------------------------------------------
   (3) بيانات اعتماد خدمة الويب لكل موديول
   وجود CLIENT_ID/KEY تحت 74 و 80 = الأجهزة سلكت مسار التفعيل الرسمي
   (وليس إدخالاً خاماً). قارن EXP_DATE و USER_ID.
   --------------------------------------------------------------------- */
SELECT MOD_ID,
       CLIENT_ID,
       USER_ID,
       EXP_DATE,
       CASE WHEN CLIENT_KEY IS NOT NULL THEN 'نعم' ELSE 'لا' END AS يملك_مفتاح
FROM   IAS_SYS.IAS_MOB_APP_WS
ORDER  BY MOD_ID;


/* ---------------------------------------------------------------------
   (4) ملف الترخيص: كل صفوفه وكمياته وحالته
   انتبه لـ MOD_ID في صف الرخصة مقابل MOD_ID في الأجهزة (0 مقابل 74/80),
   ولوجود أكثر من صف ترخيص، وقيمة LICENSE_MODULES.
   --------------------------------------------------------------------- */
SELECT REQ_ID,
       MOD_ID,
       REQ_STATUS,
       REQ_APP_STATUS,
       REQ_USER_NO,
       REQ_POS_SER_NO,
       REQ_POS_PC_NO,
       REQ_LAPTOP_NO,
       LICENSE_MODULES,
       REQ_VER_NO,
       REQ_SER_NO
FROM   IAS_SYS.IAS_LICENSES_DETAILS
ORDER  BY REQ_ID;


/* ---------------------------------------------------------------------
   (5) تجميع الإدخال حسب الطرفية والتوقيت
   توقيتات متطابقة/متقاربة من نفس الطرفية = إدخال مجمّع خارج المسار الطبيعي.
   --------------------------------------------------------------------- */
SELECT UP_TRMNL_NM                              AS الطرفية,
       TO_CHAR(ACTIVATION_DATE,'YYYY-MM-DD HH24:MI') AS لحظة_التفعيل,
       COUNT(*)                                 AS عدد_الأجهزة
FROM   IAS_SYS.IAS_OBJ_HND_DVC
GROUP  BY UP_TRMNL_NM, TO_CHAR(ACTIVATION_DATE,'YYYY-MM-DD HH24:MI')
ORDER  BY لحظة_التفعيل;


/* ---------------------------------------------------------------------
   (6) الأنظمة/المنشآت المسجّلة (ERP systems)
   كم نظاماً معرّفاً؟ تعدّد الأنظمة قد يفسّر تعدّد الموديولات.
   --------------------------------------------------------------------- */
SELECT SYS_NO,
       SYS_CODE,
       SYS_PARNT,
       CASE NVL(INACTIVE,0) WHEN 1 THEN 'موقوف' ELSE 'نشط' END AS الحالة,
       NOTES
FROM   IAS_SYS.S_ERP_SYSTEM
ORDER  BY SYS_NO;


/* ---------------------------------------------------------------------
   (7) سجل النظام حول فترة التفعيل (06-07 / 07 / 2026)
   ابحث عن أي عملية مرتبطة بالأجهزة/الترخيص في تلك النافذة الزمنية.
   عدّل التواريخ حسب ما يظهر في الاستعلام (1).
   --------------------------------------------------------------------- */
SELECT LOG_DATE,
       F_SYS,
       DOC_TYPE,
       LOG_DESC,
       BRN_NO,
       BRN_YEAR
FROM   IAS_SYS.IAS_LOGS
WHERE  LOG_DATE BETWEEN TO_DATE('06/07/2026','DD/MM/YYYY')
                    AND TO_DATE('08/07/2026','DD/MM/YYYY')
ORDER  BY LOG_DATE;
